"""Generates the batch Makefile listing every font in the design directory."""

from __future__ import annotations

import os
from os import path

from . import repo


def list_font_names(design_dir: str) -> list[str]:
    names = [n for n in os.listdir(design_dir) if path.exists(path.join(design_dir, n, "design.png"))]
    # Largest designs first so that parallel builds finish together
    return sorted(names, key=lambda n: path.getsize(path.join(design_dir, n, "design.png")), reverse=True)


def generate_batch_makefile(design_dir: str = repo.DESIGN_DIR) -> str:
    names = list_font_names(design_dir)
    gfx_headers = [h for h in (repo.gfx_header_path(n) for n in names) if h]
    lvgl_sources = [repo.lvgl_source_path(n) for n in names]
    samples = [repo.sample_image_path(n) for n in names]

    def var(name: str, items: list[str]) -> str:
        return f"{name} =" + "".join(f" \\\n\t{item}" for item in items) + "\n\n"

    out = "# Generated by `shapofont configure`. Do not edit.\n"
    out += ".PHONY: gfx_all lvgl_all sample_all\n"
    out += ".PHONY: distclean_all distclean_gfx_all distclean_lvgl_all distclean_sample_all\n\n"
    out += var("GFX_HEADER_LIST", gfx_headers)
    out += var("LVGL_SOURCE_LIST", lvgl_sources)
    out += var("SAMPLE_IMAGE_LIST", samples)
    out += "gfx_all: $(GFX_HEADER_LIST)\n"
    out += "lvgl_all: $(LVGL_SOURCE_LIST)\n"
    out += "sample_all: $(SAMPLE_IMAGE_LIST)\n\n"

    for name in names:
        design_dir_of_font = path.join(design_dir, name)
        deps = f"{design_dir_of_font}/design.png {design_dir_of_font}/design.json $(COMMON_DEPENDENCIES)"
        gfx_header = repo.gfx_header_path(name)
        if gfx_header:
            out += f"{gfx_header}: {deps}\n"
            out += "\t@mkdir -p $(dir $@)\n"
            out += f"\t$(CMD_SHAPOFONT) convert -i {design_dir_of_font} --gfx-outdir $(dir $@)\n\n"
        out += f"{repo.lvgl_source_path(name)}: {deps}\n"
        out += "\t@mkdir -p $(dir $@)\n"
        out += f"\t$(CMD_SHAPOFONT) convert -i {design_dir_of_font} --lvgl-outdir $(dir $@)\n\n"
        out += f"{repo.sample_image_path(name)}: {deps}\n"
        out += "\t@mkdir -p $(dir $@)\n"
        out += f"\t$(CMD_SHAPOFONT) convert -i {design_dir_of_font} --sample-img $@\n\n"

    out += "distclean_all: distclean_gfx_all distclean_lvgl_all distclean_sample_all\n\n"
    out += f"distclean_gfx_all:\n\trm -f {repo.GFX_OUT_DIR}/*.h\n\n"
    out += f"distclean_lvgl_all:\n\trm -f {repo.LVGL_OUT_DIR}/*.c\n\n"
    out += f"distclean_sample_all:\n\trm -f {repo.SAMPLE_OUT_DIR}/*.png\n"
    return out


def write_batch_makefile(design_dir: str = repo.DESIGN_DIR, out_path: str = repo.BATCH_MAKEFILE) -> None:
    content = generate_batch_makefile(design_dir)
    tmp_path = out_path + ".tmp"
    with open(tmp_path, "w") as f:
        f.write(content)
    os.replace(tmp_path, out_path)
