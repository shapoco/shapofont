"""Adafruit GFXfont header generator."""

from __future__ import annotations

from .cgen import footprint_comment, format_byte_array
from .design import GrayBitmap
from .font import BitmapFont

WORD_SIZE = 2
PIXEL_THRESHOLD = 128


def align_to_word_size(size: int) -> int:
    return (size + WORD_SIZE - 1) // WORD_SIZE * WORD_SIZE


class GFXglyph:
    # uint16_t bitmapOffset; uint8_t width, height, xAdvance; int8_t xOffset, yOffset;
    STRUCT_SIZE = align_to_word_size(2 + 1 + 1 + 1 + 1 + 1)

    def __init__(self, bitmap_offset: int, width: int, height: int, x_advance: int, x_offset: int, y_offset: int):
        self.bitmap_offset = bitmap_offset
        self.width = width
        self.height = height
        self.x_advance = x_advance
        self.x_offset = x_offset
        self.y_offset = y_offset

    def generate_struct_initializer(self) -> str:
        return f"{{ 0x{self.bitmap_offset:04X}, {self.width:2d}, {self.height:2d}, {self.x_advance:2d}, {self.x_offset:2d}, {self.y_offset:3d} }}"


class GFXfont:
    # uint8_t *bitmap; GFXglyph *glyph; uint16_t first, last; uint8_t yAdvance;
    STRUCT_SIZE = align_to_word_size(2 + 2 + 2 + 2 + 1)

    def __init__(self, name: str, bitmap: list[int], glyphs: list[GFXglyph], first: int, last: int, y_advance: int, effective_pixels: int):
        self.name = name
        self.bitmap = bitmap
        self.glyphs = glyphs
        self.first = first
        self.last = last
        self.y_advance = y_advance
        self.effective_pixels = effective_pixels

    def generate_header(self) -> str:
        num_glyphs = len(self.glyphs)
        shrinked_pixels = sum(g.width * g.height for g in self.glyphs)
        bitmap_size = len(self.bitmap)
        glyph_table_size = num_glyphs * GFXglyph.STRUCT_SIZE
        total_size = bitmap_size + glyph_table_size + GFXfont.STRUCT_SIZE
        pixels_per_byte = self.effective_pixels / total_size if total_size > 0 else 0

        code = "#pragma once\n\n"
        code += "// Generated by ShapoFont (https://github.com/shapoco/shapofont)\n"
        code += "//   Pixel Count:\n"
        code += f"//     Effective: {self.effective_pixels:5d} px\n"
        code += f"//     Shrinked : {shrinked_pixels:5d} px\n"
        code += footprint_comment(
            [("Bitmap Data", bitmap_size, True), ("Glyph Table", glyph_table_size, True), ("GFXfont Struct", GFXfont.STRUCT_SIZE, False)],
            num_glyphs,
        )
        code += f"//   Memory Efficiency: {pixels_per_byte:6.3f} px/Byte\n\n"
        code += "#include <stdint.h>\n\n"
        code += "#ifdef SHAPOFONT_INCLUDE_AVR_PGMSPACE\n#include <avr/pgmspace.h>\n#endif\n\n"
        code += "#ifdef SHAPOFONT_INCLUDE_GFXFONT\n#include <gfxfont.h>\n#endif\n\n"
        code += "#ifndef SHAPOFONT_PROGMEM\n#ifdef PROGMEM\n#define SHAPOFONT_PROGMEM PROGMEM\n#else\n#define SHAPOFONT_PROGMEM\n#endif\n"
        code += "#define SHAPOFONT_PROGMEM_SELF_DEFINED\n#endif\n\n"
        code += "#ifndef SHAPOFONT_GFXFONT_NAMESPACE\n#define SHAPOFONT_GFXFONT_NAMESPACE\n#define SHAPOFONT_GFXFONT_NAMESPACE_SELF_DEFINED\n#endif\n\n"
        code += f"const uint8_t {self.name}Bitmaps[] SHAPOFONT_PROGMEM = {{\n"
        code += format_byte_array(self.bitmap)
        code += "};\n\n"
        code += f"const SHAPOFONT_GFXFONT_NAMESPACE GFXglyph {self.name}Glyphs[] SHAPOFONT_PROGMEM = {{\n"
        for glyph in self.glyphs:
            code += f"  {glyph.generate_struct_initializer()},\n"
        code += "};\n\n"
        code += f"const SHAPOFONT_GFXFONT_NAMESPACE GFXfont {self.name} SHAPOFONT_PROGMEM = {{\n"
        code += f"  (uint8_t*){self.name}Bitmaps,\n"
        code += f"  (GFXglyph*){self.name}Glyphs,\n"
        code += f"  0x{self.first:02X},\n"
        code += f"  0x{self.last:02X},\n"
        code += f"  {self.y_advance}\n"
        code += "};\n\n"
        code += "#ifdef SHAPOFONT_PROGMEM_SELF_DEFINED\n#undef SHAPOFONT_PROGMEM\n#endif\n\n"
        code += "#ifdef SHAPOFONT_GFXFONT_NAMESPACE_SELF_DEFINED\n#undef SHAPOFONT_GFXFONT_NAMESPACE\n#endif\n"
        return code


def pack_bitmap_1bpp(bmp: GrayBitmap, x0: int, y0: int, w: int, h: int) -> list[int]:
    """Pack a sub-rectangle as a continuous MSB-first bit stream (GFXfont layout)."""
    packed: list[int] = []
    byte = 0
    i_bit = 7
    for y in range(h):
        for x in range(w):
            if bmp.get(x0 + x, y0 + y) >= PIXEL_THRESHOLD:
                byte |= 1 << i_bit
            if i_bit == 0:
                packed.append(byte)
                byte = 0
                i_bit = 7
            else:
                i_bit -= 1
    if i_bit != 7:
        packed.append(byte)
    return packed


class GFXfontBuilder:
    def __init__(self, name: str, y_advance: int):
        self.name = name
        self.y_advance = y_advance
        self.bitmaps: dict[int, list[int]] = {}
        self.glyphs: dict[int, GFXglyph] = {}
        self.effective_pixels = 0

    def add_glyph(self, code: int, bmp: GrayBitmap, x_offset: int, y_offset: int, x_advance: int) -> None:
        self.effective_pixels += bmp.width * bmp.height
        box = bmp.bounding_box(PIXEL_THRESHOLD)
        if box is None:
            self.bitmaps[code] = []
            self.glyphs[code] = GFXglyph(0, 0, 0, x_advance, x_offset, y_offset)
            return
        x_min, y_min, w, h = box
        self.bitmaps[code] = pack_bitmap_1bpp(bmp, x_min, y_min, w, h)
        self.glyphs[code] = GFXglyph(0, w, h, x_advance, x_offset + x_min, y_offset + y_min)

    def build(self) -> GFXfont:
        codes = sorted(self.bitmaps)
        code_first, code_last = codes[0], codes[-1]

        glyphs: list[GFXglyph] = []
        bitmap: list[int] = []
        for code in range(code_first, code_last + 1):
            if code in self.glyphs:
                glyph = self.glyphs[code]
                glyph.bitmap_offset = len(bitmap)
                bitmap += self.bitmaps[code]
            else:
                glyph = GFXglyph(0, 0, 0, 0, 0, 0)
            glyphs.append(glyph)

        bitmap = self._deduplicate(bitmap)
        return GFXfont(self.name, bitmap, glyphs, code_first, code_last, self.y_advance, self.effective_pixels)

    def _deduplicate(self, bitmap: list[int]) -> list[int]:
        """Remove glyph bitmaps that also occur elsewhere in the array, re-pointing them there."""
        deleted_codes: set[int] = set()
        for _ in range(10):
            num_deleted = 0
            for code, glyph in self.glyphs.items():
                size = len(self.bitmaps[code])
                if code in deleted_codes or size <= 0:
                    continue
                orig_offset = glyph.bitmap_offset
                pattern = bitmap[orig_offset : orig_offset + size]

                new_offset = -1
                for i in range(0, orig_offset - size + 1):
                    if bitmap[i : i + size] == pattern:
                        new_offset = i
                        break
                if new_offset < 0:
                    for i in range(orig_offset + size, len(bitmap) - size + 1):
                        if bitmap[i : i + size] == pattern:
                            new_offset = i
                            break
                if new_offset < 0:
                    continue

                # Other glyphs whose bitmaps live inside the block to be removed
                perfect_referers: list[GFXglyph] = []
                partially_overlapped = False
                for ref_code, ref_glyph in self.glyphs.items():
                    ref_size = len(self.bitmaps[ref_code])
                    if ref_code == code or ref_size <= 0:
                        continue
                    ref_offset = ref_glyph.bitmap_offset
                    overlapped = ref_offset < orig_offset + size and orig_offset < ref_offset + ref_size
                    included = orig_offset <= ref_offset and ref_offset + ref_size <= orig_offset + size
                    if included:
                        perfect_referers.append(ref_glyph)
                    elif overlapped:
                        partially_overlapped = True
                if partially_overlapped:
                    continue

                glyph.bitmap_offset = new_offset
                for ref_glyph in perfect_referers:
                    ref_glyph.bitmap_offset += new_offset - orig_offset

                bitmap = bitmap[:orig_offset] + bitmap[orig_offset + size :]
                for ref_code, ref_glyph in self.glyphs.items():
                    if len(self.bitmaps[ref_code]) > 0 and ref_glyph.bitmap_offset >= orig_offset + size:
                        ref_glyph.bitmap_offset -= size

                deleted_codes.add(code)
                num_deleted += 1
            if num_deleted == 0:
                break
        return bitmap


def generate_gfxfont(font: BitmapFont) -> str:
    """Generate the GFXfont header source for a 1 bpp font."""
    if font.bits_per_pixel != 1:
        raise ValueError(f"{font.full_name}: GFXfont supports only bits_per_pixel=1 (got {font.bits_per_pixel}).")
    builder = GFXfontBuilder(font.full_name, font.line_height)
    for glyph in font.glyphs.values():
        builder.add_glyph(glyph.code, glyph.bmp, font.x_offset_of(glyph), -font.baseline, font.x_advance_of(glyph))
    return builder.build().generate_header()
